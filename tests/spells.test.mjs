import { resolve } from '../js/spells.js';
import { ROOTS, SECRETS, BY_ID } from '../js/lexicon.js';
import assert from 'node:assert/strict';
const t = (w, kind) => { const r = resolve(w); assert.equal(r.kind, kind, `${w.join(' ')} -> ${JSON.stringify(r)}`); return r; };
assert.equal(ROOTS.length, 47);
assert.equal(ROOTS.filter(r=>r.role==='S').length, 15);
assert.equal(ROOTS.filter(r=>r.role==='F').length, 27);
assert.equal(ROOTS.filter(r=>r.role==='M').length, 5);
for (const s of SECRETS) for (const w of s.words) assert.ok(BY_ID[w], 'unknown word ' + w);
t(['Ignis'], 'solo');
assert.match(t(['Inan'], 'fizzle').hint, /Vorte/);
t(['Velox'], 'fizzle');
t(['Scut','Ignis'], 'secret');
t(['Ignis','Scut'], 'secret');
t(['Lum','Umbra'], 'cancel');
t(['Fulg','Sect'], 'combo');
t(['Ignis','Aqua'], 'fizzle');
t(['Aug','Ignis'], 'fizzle');
t(['Aug','Umbra'], 'secret');
t(['Cura','Vita','Velox'], 'secret');
const r = t(['Furo','Ignis','Rupt'], 'combo'); console.log(r.name, '|', r.effect);
console.log(resolve(['Fulg','Sect']).effect, '|', resolve(['Aetern','Aqua','Scut']));
t(['Aug','Minu','Ignis'], 'cancel');
console.log('all passed');
